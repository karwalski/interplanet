(* ECMAScript \s: WhiteSpace and LineTerminator code points *)
let is_js_space cp =
  cp = 0x20 || (cp >= 0x09 && cp <= 0x0D) || cp = 0xA0 || cp = 0x1680
  || (cp >= 0x2000 && cp <= 0x200A) || cp = 0x2028 || cp = 0x2029
  || cp = 0x202F || cp = 0x205F || cp = 0x3000 || cp = 0xFEFF

(* JS toUpperCase of one code point: 1 to 3 code points *)
let upper_cp cp =
  if cp >= 0x61 && cp <= 0x7A then [ cp - 0x20 ]
  else if cp < 0xB5 then [ cp ]
  else
    match Array.find_opt (fun (c, _) -> c = cp) upper_special with
    | Some (_, up) -> up
    | None ->
      let n = Array.length upper_runs in
      let rec go i =
        if i >= n then [ cp ]
        else
          let first, last, stride, delta = upper_runs.(i) in
          if cp < first then [ cp ]
          else if cp <= last && (cp - first) mod stride = 0 then [ cp + delta ]
          else go (i + 1)
      in
      go 0

(* The code points of a UTF-8 (or WTF-8) string; a surrogate encoded as
   three bytes is one code point, an invalid byte is itself. *)
let code_points (s : string) : int list =
  let n = String.length s in
  let byte i = Char.code s.[i] in
  let cont i = i < n && byte i land 0xC0 = 0x80 in
  let rec go i acc =
    if i >= n then List.rev acc
    else
      let b = byte i in
      if b < 0x80 then go (i + 1) (b :: acc)
      else if b land 0xE0 = 0xC0 && cont (i + 1) then
        go (i + 2) ((((b land 0x1F) lsl 6) lor (byte (i + 1) land 0x3F)) :: acc)
      else if b land 0xF0 = 0xE0 && cont (i + 1) && cont (i + 2) then
        go (i + 3)
          ((((b land 0x0F) lsl 12) lor ((byte (i + 1) land 0x3F) lsl 6) lor (byte (i + 2) land 0x3F))
           :: acc)
      else if b land 0xF8 = 0xF0 && cont (i + 1) && cont (i + 2) && cont (i + 3) then
        go (i + 4)
          ((((b land 0x07) lsl 18) lor ((byte (i + 1) land 0x3F) lsl 12)
            lor ((byte (i + 2) land 0x3F) lsl 6) lor (byte (i + 3) land 0x3F))
           :: acc)
      else go (i + 1) (b :: acc)
  in
  go 0 []

(* Append a code point as UTF-8 (a surrogate as its WTF-8 bytes) *)
let add_cp buf cp =
  let add b = Buffer.add_char buf (Char.chr b) in
  if cp < 0x80 then add cp
  else if cp < 0x800 then (add (0xC0 lor (cp lsr 6)); add (0x80 lor (cp land 0x3F)))
  else if cp < 0x10000 then begin
    add (0xE0 lor (cp lsr 12)); add (0x80 lor ((cp lsr 6) land 0x3F)); add (0x80 lor (cp land 0x3F))
  end else begin
    add (0xF0 lor (cp lsr 18)); add (0x80 lor ((cp lsr 12) land 0x3F));
    add (0x80 lor ((cp lsr 6) land 0x3F)); add (0x80 lor (cp land 0x3F))
  end

(* The first n UTF-16 code units of the code points cps, as UTF-8. When the
   cut splits a surrogate pair JS keeps the lone high surrogate, and so does
   this, as WTF-8 (planIdWtf8Hex in spec/golden/plan-id-prefixes.json). *)
let take_units (cps : int list) (n : int) : string =
  let buf = Buffer.create 32 in
  let rec go units = function
    | [] -> ()
    | cp :: rest ->
      let need = if cp >= 0x10000 then 2 else 1 in
      if units + need > n then begin
        if units < n then add_cp buf (0xD800 + ((cp - 0x10000) lsr 10))
      end else begin
        add_cp buf cp;
        go (units + need) rest
      end
  in
  go 0 cps;
  Buffer.contents buf

(* s.toUpperCase() with JavaScript semantics *)
let js_uppercase (s : string) : string =
  let buf = Buffer.create (String.length s) in
  List.iter (fun cp -> List.iter (add_cp buf) (upper_cp cp)) (code_points s);
  Buffer.contents buf

(* s.slice(0, n) in UTF-16 code units *)
let utf16_slice (s : string) (n : int) : string = take_units (code_points s) n

(* name.replace(/\s+/g, '').toUpperCase().slice(0, n) *)
let plan_id_token (name : string) (n : int) : string =
  let cps = List.filter (fun cp -> not (is_js_space cp)) (code_points name) in
  take_units (List.concat_map upper_cp cps) n
