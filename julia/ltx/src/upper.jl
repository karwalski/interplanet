# JavaScript String.prototype.toUpperCase for the planId name tokens
# (LTX-SPECIFICATION.md section 4.3, issue #37).
#
# Base.uppercase applies only the 1:1 (simple) Unicode case mappings, so
# 'ß', 'ﬁ', 'ŉ', 'ΐ', 'ᾳ', 'և' ... stay unchanged or map to one character
# where JS gives "SS", "FI", "ʼN", "Ϊ́", "ΑΙ", "ԵՒ". js_uppercase adds the
# unconditional special casings from the generated table below.

"""
    js_uppercase(s) -> String

`s.toUpperCase()` with JavaScript semantics: locale-independent, full
Unicode case mapping (special casing included).
"""
function js_uppercase(s::AbstractString)::String
    io = IOBuffer()
    for c in s
        sp = isvalid(c) ? get(_UPPER_SPECIAL, UInt32(c), nothing) : nothing
        if sp === nothing
            print(io, isvalid(c) ? uppercase(c) : c)
        else
            for u in sp
                print(io, Char(u))
            end
        end
    end
    return String(take!(io))
end

