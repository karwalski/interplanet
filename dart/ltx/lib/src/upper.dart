/// JavaScript String.prototype.toUpperCase and the planId name tokens
/// (LTX-SPECIFICATION.md section 4.3, issue #37).
///
/// Dart's String.toUpperCase is not JS toUpperCase: it applies only 1:1
/// mappings, from tables that predate Unicode 7 ('ƛ', 'ɐ', 'ꞵ' ... are not
/// mapped), and no special casing ('ß', 'ﬁ', 'ŉ', 'ΐ', 'ᾳ', 'և' stay or map
/// to one character where JS gives 'SS', 'FI', 'ʼN', 'Ϊ́', 'ΑΙ', 'ԵՒ').
/// jsToUpperCase uses the table below, generated from JS toUpperCase over
/// every code point by scripts/conformance/gen-upper-tables.js.
library;

/// Upper-case mapping of one code point, JS semantics: 1 to 3 code points.
List<int> jsUpperRune(int cp) {
  final sp = _upperSpecial[cp];
  if (sp != null) return sp;
  for (final r in _upperRuns) {
    if (cp < r[0]) break;
    if (cp <= r[1] && (cp - r[0]) % r[2] == 0) return [cp + r[3]];
  }
  return [cp];
}

/// `s.toUpperCase()` with JavaScript semantics (locale-independent, full
/// Unicode case mapping).
String jsToUpperCase(String s) {
  final out = <int>[];
  for (final r in s.runes) {
    if (r < 0x61) {
      out.add(r);
    } else if (r <= 0x7A) {
      out.add(r - 0x20);
    } else {
      out.addAll(jsUpperRune(r));
    }
  }
  return String.fromCharCodes(out);
}

/// `name.replace(/\s+/g, '').toUpperCase().slice(0, n)`. Dart's RegExp \s
/// is the ECMAScript set, and Dart strings are UTF-16, so the slice keeps a
/// lone high surrogate exactly as JS does.
String planIdToken(String name, int n) {
  final s = jsToUpperCase(name.replaceAll(RegExp(r'\s+'), ''));
  return s.length > n ? s.substring(0, n) : s;
}

