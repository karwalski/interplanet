#!/usr/bin/env node
/**
 * gen-upper-tables.js: Unicode upper-case tables for the LTX ports whose
 * language has no full Unicode case mapping (issue #37).
 *
 * The planId HOSTSTR / NODESTR (docs/LTX-SPECIFICATION.md section 4.3) use
 * JS String.prototype.toUpperCase: locale-independent, full Unicode case
 * mapping, including the one-to-many special casings (ß to SS, ﬁ to FI,
 * ΐ to Ϊ́ ...). The tables are derived from the running node's toUpperCase
 * over every code point, so they are exactly JS semantics for that node's
 * Unicode version (printed in the generated block).
 *
 *   SPECIAL  code point -> 2 or 3 code points (SpecialCasing.txt, unconditional)
 *   RUNS     simple 1:1 mappings compressed as (first, last, stride, delta):
 *            cp in first..last with (cp - first) % stride == 0 maps to cp + delta
 *
 * Julia, whose Base.uppercase(::Char) has current 1:1 mappings but no
 * special casing, takes SPECIAL only; the others (C, OCaml, R, Lua, Zig, and
 * Dart, whose String.toUpperCase tables predate Unicode 7) take both.
 *
 * Usage:
 *   node scripts/conformance/gen-upper-tables.js --lang c        print one block
 *   node scripts/conformance/gen-upper-tables.js --write         rewrite every target
 *   node scripts/conformance/gen-upper-tables.js --check         exit 1 if a target is stale
 * A target file holds its block between lines containing
 * "BEGIN GENERATED UPPER TABLE" and "END GENERATED UPPER TABLE".
 */
'use strict';

const fs = require('fs');
const path = require('path');

const ROOT = path.resolve(__dirname, '..', '..');

function buildTables() {
  const simple = [];
  const special = [];
  for (let cp = 0; cp <= 0x10FFFF; cp++) {
    if (cp >= 0xD800 && cp <= 0xDFFF) continue;
    const s = String.fromCodePoint(cp);
    const u = s.toUpperCase();
    if (u === s) continue;
    const cps = [...u].map(c => c.codePointAt(0));
    if (cps.length === 1) simple.push([cp, cps[0]]);
    else special.push([cp, cps]);
  }
  const runs = [];
  for (const [cp, up] of simple) {
    const d = up - cp;
    const r = runs[runs.length - 1];
    if (r && r.delta === d) {
      if (r.first === r.last && (cp - r.first === 1 || cp - r.first === 2)) {
        r.stride = cp - r.first; r.last = cp; continue;
      }
      if (r.first !== r.last && cp === r.last + r.stride) { r.last = cp; continue; }
    }
    runs.push({ first: cp, last: cp, stride: 1, delta: d });
  }
  return { runs, special };
}

const { runs, special } = buildTables();
const VERSION = `Unicode ${process.versions.unicode} (node ${process.versions.node})`;
const HEADER = `Generated by scripts/conformance/gen-upper-tables.js from JS toUpperCase, ${VERSION}.`;

const hex = n => '0x' + n.toString(16).toUpperCase();
function rows(items, perLine, fmt, indent, sep) {
  const out = [];
  for (let i = 0; i < items.length; i += perLine) {
    out.push(indent + items.slice(i, i + perLine).map(fmt).join(sep));
  }
  return out;
}
const pad3 = a => [a[0], a[1] || 0, a[2] || 0];

const FORMATS = {
  // C: static const arrays.
  c: () => [
    `/* ${HEADER} */`,
    `#define ITX_UPPER_RUNS ${runs.length}`,
    `#define ITX_UPPER_SPECIAL ${special.length}`,
    'static const int32_t itx_upper_runs[ITX_UPPER_RUNS][4] = { /* first, last, stride, delta */',
    ...rows(runs, 3, r => `{${hex(r.first)},${hex(r.last)},${r.stride},${r.delta}}`, '    ', ', ').map(l => l + ','),
    '};',
    'static const uint32_t itx_upper_special[ITX_UPPER_SPECIAL][4] = { /* cp, up to 3 code points (0 = none) */',
    ...rows(special, 4, ([cp, u]) => `{${hex(cp)},${pad3(u).map(hex).join(',')}}`, '    ', ', ').map(l => l + ','),
    '};',
  ],
  // OCaml: arrays of tuples.
  ocaml: () => [
    `(* ${HEADER} *)`,
    '(* first, last, stride, delta *)',
    'let upper_runs = [|',
    ...rows(runs, 3, r => `(${hex(r.first)}, ${hex(r.last)}, ${r.stride}, ${r.delta < 0 ? '(' + r.delta + ')' : r.delta})`, '  ', '; ').map(l => l + ';'),
    '|]',
    '(* code point, up to 3 code points *)',
    'let upper_special = [|',
    ...rows(special, 3, ([cp, u]) => `(${hex(cp)}, [${u.map(hex).join('; ')}])`, '  ', '; ').map(l => l + ';'),
    '|]',
  ],
  // R: integer vectors (runs flattened by 4, specials by 4 with 0 padding).
  r: () => [
    `# ${HEADER}`,
    '# first, last, stride, delta (flattened, 4 per run)',
    '.ltx_upper_runs <- matrix(c(',
    ...rows(runs, 3, r => `${r.first}L, ${r.last}L, ${r.stride}L, ${r.delta}L`, '  ', ', ').map((l, i, a) => l + (i < a.length - 1 ? ',' : '')),
    '), ncol = 4L, byrow = TRUE)',
    '# code point, up to 3 code points (0 = none)',
    '.ltx_upper_special <- matrix(c(',
    ...rows(special, 4, ([cp, u]) => [cp, ...pad3(u)].map(x => x + 'L').join(', '), '  ', ', ').map((l, i, a) => l + (i < a.length - 1 ? ',' : '')),
    '), ncol = 4L, byrow = TRUE)',
  ],
  // Lua: tables.
  lua: () => [
    `-- ${HEADER}`,
    '-- { first, last, stride, delta }',
    'local UPPER_RUNS = {',
    ...rows(runs, 3, r => `{${hex(r.first)},${hex(r.last)},${r.stride},${r.delta}}`, '  ', ', ').map(l => l + ','),
    '}',
    '-- [code point] = { code points }',
    'local UPPER_SPECIAL = {',
    ...rows(special, 3, ([cp, u]) => `[${hex(cp)}]={${u.map(hex).join(',')}}`, '  ', ', ').map(l => l + ','),
    '}',
  ],
  // Zig: const arrays of structs.
  zig: () => [
    `// ${HEADER}`,
    'const UpperRun = struct { first: u21, last: u21, stride: u21, delta: i32 };',
    'const UpperSpecial = struct { cp: u21, up: [3]u21, len: u2 };',
    'const upper_runs = [_]UpperRun{',
    ...rows(runs, 1, r => `.{ .first = ${hex(r.first)}, .last = ${hex(r.last)}, .stride = ${r.stride}, .delta = ${r.delta} }`, '    ', ', ').map(l => l + ','),
    '};',
    'const upper_special = [_]UpperSpecial{',
    ...rows(special, 1, ([cp, u]) => `.{ .cp = ${hex(cp)}, .up = .{ ${pad3(u).map(hex).join(', ')} }, .len = ${u.length} }`, '    ', ', ').map(l => l + ','),
    '};',
  ],
  // Dart: String.toUpperCase has old 1:1 tables and no special casing.
  dart: () => [
    `// ${HEADER}`,
    '// [first, last, stride, delta]',
    'const List<List<int>> _upperRuns = [',
    ...rows(runs, 3, r => `[${hex(r.first)}, ${hex(r.last)}, ${r.stride}, ${r.delta}]`, '  ', ', ').map(l => l + ','),
    '];',
    '// Special casing: code point -> code points.',
    'const Map<int, List<int>> _upperSpecial = {',
    ...rows(special, 3, ([cp, u]) => `${hex(cp)}: [${u.map(hex).join(', ')}]`, '  ', ', ').map(l => l + ','),
    '};',
  ],
  // Julia: special casing only (Base.uppercase(::Char) does the 1:1 mappings).
  julia: () => [
    `# ${HEADER}`,
    '# Special casing only: code point => code points.',
    'const _UPPER_SPECIAL = Dict{UInt32,Vector{UInt32}}(',
    ...rows(special, 3, ([cp, u]) => `${hex(cp)} => UInt32[${u.map(hex).join(', ')}]`, '    ', ', ').map((l, i, a) => l + (i < a.length - 1 ? ',' : '')),
    ')',
  ],
};

// Files that carry a generated block (between the BEGIN/END marker lines).
const TARGETS = {
  c: 'c/ltx/src/itx_plan_json.c',
  ocaml: 'ocaml/ltx/lib/upper.ml',
  r: 'r/ltx/R/ltx.R',
  lua: 'lua/ltx/src/interplanet_ltx.lua',
  zig: ['zig/ltx/src/interplanet_ltx.zig', 'zig/ltx/src/ltx_v11.zig'],
  dart: 'dart/ltx/lib/src/upper.dart',
  julia: 'julia/ltx/src/upper.jl',
};

function splice(text, block, file) {
  const lines = text.split('\n');
  const b = lines.findIndex(l => l.includes('BEGIN GENERATED UPPER TABLE'));
  const e = lines.findIndex(l => l.includes('END GENERATED UPPER TABLE'));
  if (b < 0 || e < b) throw new Error(`${file}: no BEGIN/END GENERATED UPPER TABLE markers`);
  return [...lines.slice(0, b + 1), ...block, ...lines.slice(e)].join('\n');
}

const args = process.argv.slice(2);
const li = args.indexOf('--lang');
if (li >= 0) {
  const f = FORMATS[args[li + 1]];
  if (!f) { console.error(`unknown --lang; one of ${Object.keys(FORMATS).join(', ')}`); process.exit(2); }
  console.log(f().join('\n'));
} else if (args.includes('--write') || args.includes('--check')) {
  let stale = 0;
  const targets = Object.entries(TARGETS).flatMap(([lang, rel]) => [].concat(rel).map(r => [lang, r]));
  for (const [lang, rel] of targets) {
    const file = path.join(ROOT, rel);
    if (!fs.existsSync(file)) { console.log(`skip ${rel} (missing)`); continue; }
    const old = fs.readFileSync(file, 'utf8');
    if (!old.includes('BEGIN GENERATED UPPER TABLE')) { console.log(`skip ${rel} (no markers)`); stale++; continue; }
    const next = splice(old, FORMATS[lang](), rel);
    // The Unicode/node version line alone does not make a block stale.
    const norm = t => t.replace(/Generated by .* from JS toUpperCase, .*\./g, '');
    if (norm(next) === norm(old)) { console.log(`ok    ${rel}`); continue; }
    if (args.includes('--check')) { console.log(`stale ${rel}`); stale++; continue; }
    fs.writeFileSync(file, next);
    console.log(`wrote ${rel}`);
  }
  process.exit(stale ? 1 : 0);
} else {
  console.log(`${runs.length} runs, ${special.length} special casings (${VERSION})`);
  console.log('usage: --lang <' + Object.keys(FORMATS).join('|') + '> | --write | --check');
}
